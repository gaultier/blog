    // Hands out one byte at a time, so the request spans many `read` calls.
    struct DripReader {
        data: Vec<u8>,
        pos: usize,
    }

    impl Read for DripReader {
        fn read(&mut self, buf: &mut [u8]) -> io::Result<usize> {
            if self.pos >= self.data.len() || buf.is_empty() {
                return Ok(0);
            }
            buf[0] = self.data[self.pos];
            self.pos += 1;
            Ok(1)
        }
    }

