// A panic while holding the lock poisons it. The data it guards is a counter
// that is still perfectly valid, and refusing to serve live-reload for the rest
// of the session because one rebuild panicked helps nobody.
fn lock_ignore_poison<T>(lock: &Mutex<T>) -> std::sync::MutexGuard<'_, T> {
    lock.lock().unwrap_or_else(|err| err.into_inner())
}

fn watch(mtx_cond: Arc<(Mutex<u64>, Condvar)>, cache: &mut HashMap<u64, Article>) {
    let (etx, erx) = std::sync::mpsc::channel::<notify::Result<notify::Event>>();
    let mut watcher = notify::recommended_watcher(etx).unwrap();
    watcher
        .watch(Path::new("."), RecursiveMode::NonRecursive)
        .unwrap();
    for res in erx {
        let event = match res {
            Ok(event) => event,
            Err(e) => {
                println!("watch error: {:?}", e);
                continue;
            }
        };

        // Many editors save by writing a temporary file and renaming it over
        // the target, which never produces `Modify(Data(..))`: on macOS
        // FSEvents it shows up as `Create` or `Modify(Name(..))`. Only
        // listening for data modifications missed those saves entirely.
        let interesting = matches!(
            event.kind,
            EventKind::Create(_)
                | EventKind::Modify(ModifyKind::Any | ModifyKind::Data(_) | ModifyKind::Name(_))
        );
        if !interesting {
            continue;
        }

        let (lock, cvar) = &*mtx_cond;
        let mut generation = lock_ignore_poison(lock);
        for path in event.paths {
            // A watched path always has a final component, but do not bet the
            // watcher thread on it.
            let Some(file_name) = path.file_name() else {
                continue;
            };
            let file_name_str = file_name.to_string_lossy();

            if file_name == AsRef::<Path>::as_ref("header.html")
                || file_name == AsRef::<Path>::as_ref("footer.html")
            {
                println!("🔄 header/footer changed: {}", file_name_str);
                if let Err(err) = generate_all(cache) {
                    eprintln!("err: {:?}", err);
                }
                *generation += 1;
                cvar.notify_all();
            }
            if path.extension() == Some("js".as_ref())
                || path.extension() == Some("css".as_ref())
                || path.extension() == Some("svg".as_ref())
                || path.extension() == Some("png".as_ref())
                || path.extension() == Some("webm".as_ref())
                || path.extension() == Some("mp4".as_ref())
                || path.extension() == Some("jpeg".as_ref())
                || path.extension() == Some("ico".as_ref())
                || path.extension() == Some("gif".as_ref())
            {
                println!("🔄 asset changed: {}", file_name_str);

                *generation += 1;
                cvar.notify_all();
            }

            if path.extension() == Some("md".as_ref())
                // Ignore some files:
                && !IGNORED_MARKDOWN_FILES
                    .iter()
                    .any(|ignored| file_name == AsRef::<Path>::as_ref(ignored))
            {
                println!("🔄 md file changed: {}", file_name_str);
                if let Err(err) = generate_all(cache) {
                    eprintln!("err: {:?}", err);
                }

                *generation += 1;
                cvar.notify_all();
            }
        }
    }

    println!("end of file watch ");
}

// Minimal percent-decoding: a browser encodes spaces and non-ASCII bytes in
// asset names, and the file on disk is not called `my%20file.png`.
fn percent_decode(s: &str) -> Option<String> {
    if !s.contains('%') {
        return Some(s.to_owned());
    }

    let bytes = s.as_bytes();
    let mut res = Vec::with_capacity(bytes.len());
    let mut i = 0;
    while i < bytes.len() {
        if bytes[i] == b'%' {
            res.push(u8::from_str_radix(s.get(i + 1..i + 3)?, 16).ok()?);
            i += 3;
        } else {
            res.push(bytes[i]);
            i += 1;
        }
    }

    String::from_utf8(res).ok()
}

// Resolve a URL path to a file inside `root`, or `None` if it points outside of
// it. Everything but plain file/directory names is refused rather than
// resolved: there is nothing above the blog root worth serving.
fn http_resolve_path(root: &Path, url_path: &str) -> Option<PathBuf> {
    // A query string or a fragment is not part of the path.
    let url_path = url_path
        .split_once(['?', '#'])
        .map_or(url_path, |(path, _)| path);
    let rel = url_path.strip_prefix("/blog/")?;
    // Decode before validating the components, so that an escaped `..` is
    // caught by the loop below rather than sneaking through it.
    let rel = percent_decode(rel)?;

    let mut res = root.to_path_buf();
    for comp in Path::new(&rel).components() {
        match comp {
            std::path::Component::Normal(c) => res.push(c),
            _ => return None,
        }
    }

    // Symlinks can still point outside of the root, so check the real path too.
    let res = res.canonicalize().ok()?;
    if !res.starts_with(root) {
        return None;
    }

    Some(res)
}

fn get_content_type(path: &Path) -> &'static str {
    let extension = match path.extension() {
        None => return "text/plain",
        Some(e) => e,
    };

    match extension.to_str().unwrap() {
        "js" => "application/javascript",
        "gif" => "image/gif",
        "jpg" => "image/jpeg",
        "jpeg" => "image/jpeg",
        "ico" => "image/vnd.microsoft.icon",
        "png" => "image/png",
        "pdf" => "application/pdf",
        "htm" => "text/html; charset=utf8",
        "html" => "text/html; charset=utf8",
        "txt" => "text/plain; charset=utf8",
        "svg" => "image/svg+xml",
        "css" => "text/css; charset=utf-8",
        "mp4" => "video/mp4",
        _ => "text/plain; charset=utf8",
    }
}

fn http_serve<F>(handler: F) -> io::Result<()>
where
    F: Fn(httparse::Request<'_, '_>, TcpStream) + Send + Sync + Clone + 'static,
{
    let addr: SocketAddr = "127.0.0.1:8001".parse().unwrap();

    let listener = TcpListener::bind(addr)?;
    println!("Open: http://{}/blog", addr);

    loop {
        let (mut stream, _) = listener.accept()?;

        let handler = handler.clone();
        thread::spawn(move || {
            // Do not let a stalled client hold a thread forever.
            if let Err(err) = stream.set_read_timeout(Some(HTTP_READ_TIMEOUT)) {
                eprintln!("http: failed to set the read timeout: {}", err);
                return;
            }

            let mut req_bytes: Vec<u8> = Vec::with_capacity(10 * 1024); // 10 KiB.
            loop {
                // Grow when full: a request bigger than the initial capacity
                // used to end up handing `read()` an empty slice, which reads 0
                // and drops the connection without ever answering.
                if req_bytes.len() == req_bytes.capacity() {
                    if req_bytes.capacity() >= HTTP_REQUEST_SIZE_MAX {
                        eprintln!("http: request bigger than {} bytes", HTTP_REQUEST_SIZE_MAX);
                        return;
                    }
                    req_bytes.reserve(req_bytes.capacity());
                }
                let cap = req_bytes.capacity();

                let old_len = req_bytes.len();
                // Zero the spare capacity so that `read()` gets a real `&mut [u8]`.
                // This does not reallocate since `len <= capacity`.
                req_bytes.resize(cap, 0);
                let read_count = match stream.read(&mut req_bytes[old_len..]) {
                    Ok(read_count) => read_count,
                    Err(err) => {
                        eprintln!("http: failed to read request: {}", err);
                        return;
                    }
                };
                req_bytes.truncate(old_len + read_count);
                if read_count == 0 {
                    eprintln!("http: read 0");
                    return;
                }

                let mut headers = [httparse::EMPTY_HEADER; 1024];
                let mut req = httparse::Request::new(&mut headers);
                let req_parsed = match req.parse(&req_bytes) {
                    Ok(req_parsed) => req_parsed,
                    Err(err) => {
                        eprintln!("http: failed to parse request: {}", err);
                        return;
                    }
                };
                if !req_parsed.is_partial() {
                    handler(req, stream);
                    return;
                }
            }
        });
    }
}

fn live_reload(
    mut resp: BufWriter<TcpStream>,
    mtx_cond: Arc<(Mutex<u64>, Condvar)>,
) -> Result<(), ()> {
    write!(
        resp,
        "HTTP/1.1 200\r\nCache-Control: no-cache\r\nContent-Type: text/event-stream\r\n\r\n"
    )
    .map_err(|_| ())?;
    // The headers sit in the `BufWriter` until something flushes it, and the
    // browser will not consider the stream open before it sees them.
    resp.flush().map_err(|_| ())?;

    let (lock, cvar) = &*mtx_cond;
    let mut seen = *lock_ignore_poison(lock);

    loop {
        // Wait on the generation rather than on a bare notification: a rebuild
        // finishing between two waits used to be lost, and a spurious wakeup
        // used to send a reload event that nothing had asked for.
        let generation = {
            let guard = lock_ignore_poison(lock);
            let guard = cvar
                .wait_while(guard, |generation| *generation == seen)
                .unwrap_or_else(|err| err.into_inner());
            *guard
        };
        seen = generation;

        write!(resp, "data: foobar\n\n").map_err(|_| ())?;
        resp.flush().map_err(|_| ())?;
        println!("🔃 sse event sent");
    }
}

fn main() -> ExitCode {
    let mut args = std::env::args().skip(1);
    let arg1 = args.next();

    check_langs();

    let mut cache = HashMap::with_capacity(128);

    let mut exit_code = ExitCode::SUCCESS;
    if let Err(err) = generate_all(&mut cache) {
        eprintln!("err: {:?}", err);
        exit_code = ExitCode::FAILURE;
    }

    if let Some(arg) = arg1
        && arg == "watch"
    {
        let serve_root = std::env::current_dir()
            .and_then(|d| d.canonicalize())
            .expect("failed to resolve the current directory");

        let mtx_cond = Arc::new((Mutex::new(0u64), Condvar::new()));

        let mtx_cond2 = Arc::clone(&mtx_cond);

        thread::spawn(move || {
            watch(mtx_cond2, &mut cache);
        });

        if let Err(err) = http_serve(move |req, stream| {
            let mut resp = BufWriter::new(stream);
            match (req.method.unwrap(), req.path.unwrap()) {
                ("GET", "/blog") => {
                    // The client can vanish at any point: never panic on a write.
                    let _ = write!(
                        resp,
                        "HTTP/1.1 301\r\nLocation: /blog/index.html\r\nConnection: Close\r\n\r\n"
                    );
                }
                ("GET", "/blog/live-reload") => {
                    let _ = live_reload(resp, mtx_cond.clone());
                }
                _ => {
                    let url_path = req.path.unwrap();
                    let path = match http_resolve_path(&serve_root, url_path) {
                        Some(path) => path,
                        None => {
                            eprintln!("refused path: url_path={}", url_path);
                            let _ = write!(resp, "HTTP/1.1 404\r\nConnection: Close\r\n\r\n");
                            return;
                        }
                    };

                    let content = match std::fs::read(&path) {
                        Ok(content) => content,
                        Err(err) => {
                            eprintln!(
                                "file not found: url_path={} path={:?} err={}",
                                url_path, &path, err
                            );
                            let _ = write!(resp, "HTTP/1.1 404\r\nConnection: Close\r\n\r\n");
                            return;
                        }
                    };

                    let _ = write!(
                        resp,
                        "HTTP/1.1 200\r\nContent-Length: {}\r\nContent-Type: {}\r\n\r\n",
                        content.len(),
                        get_content_type(&path)
                    );
                    let _ = resp.write_all(&content);
                }
            };
        }) {
            eprintln!("err: http server: {}", err);
            return ExitCode::FAILURE;
        }
    }

    exit_code
}
