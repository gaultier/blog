fn tags_page_build(
    articles: &[Article],
    html_header: &[u8],
    html_footer: &[u8],
) -> anyhow::Result<Vec<u8>> {
    // The same preconditions as at the call site: this is the half that runs
    // under the unit tests.
    assert!(!html_header.is_empty());
    assert!(!html_footer.is_empty());

    let mut tag_to_articles = BTreeMap::new();

    for article in articles {
        article.assert_invariants();

        for tag in &article.tags {
            tag_to_articles
                .entry(tag.clone())
                .or_insert_with(Vec::new)
                .push(article);
        }
    }

    // Every tag of every article landed in exactly one bucket: an article
    // dropped here would silently vanish from the page rather than crash it.
    let tags_in: usize = articles.iter().map(|a| a.tags.len()).sum();
    let tags_out: usize = tag_to_articles.values().map(|v: &Vec<_>| v.len()).sum();
    assert_eq!(tags_in, tags_out);

    for tag1 in tag_to_articles.keys() {
        for tag2 in tag_to_articles.keys() {
            if tag1 != tag2 && tag1.to_lowercase() == tag2.to_lowercase() {
                bail!(
                    "similar tags detected with different case: {} vs {}",
                    tag1,
                    tag2
                );
            }
        }
    }

    let mut sb: Vec<u8> = Vec::with_capacity(64000);
    writeln!(
        sb,
        "<!DOCTYPE html>\n<html>\n<head>\n<title>Articles by tag</title>",
    )?;
    sb.extend(html_header);
    sb.extend(BACK_LINK.as_bytes());

    writeln!(sb, "\n<h1>Articles by tag</h1>\n<ul>",)?;

    for (tag, articles) in &mut tag_to_articles {
        articles.sort_by(|a, b| a.git_stat.creation_date.cmp(&b.git_stat.creation_date));

        writeln!(
            sb,
            "<li id=\"{}\"><span class=\"tag\">{}</span>: {}<ul>",
            html_slug(tag),
            text_sanitize_for_html(tag, false),
            articles.len(),
        )?;

        for a in articles {
            sb.extend(b"<li>\n");
            let (date, _time) = a
                .git_stat
                .creation_date
                .split_once("T")
                .ok_or(anyhow!("failed to parse date"))?;
            writeln!(sb, "  <span class=\"date\">{}</span>", date)?;
            writeln!(
                sb,
                "  <a href=\"{}\">{}</a>\n</li>",
                &a.html_path.to_string_lossy(),
                &a.html_title
            )?;
        }
        writeln!(sb, "</ul></li>",)?;
    }
    writeln!(sb, "</ul>",)?;

    sb.extend(html_footer);

    assert!(sb.len() > html_header.len() + html_footer.len());

    Ok(sb)
}

fn generate_article_rss(
    sb: &mut Vec<u8>,
    base_uuid: &uuid::Uuid,
    article: &Article,
) -> anyhow::Result<()> {
    // An Atom entry carries both dates and a title, all written below without
    // a fallback: `<published>` is the creation date and `<updated>` the
    // modification date, so a feed reader sees an entry updated before it was
    // published if these ever swap.
    article.assert_invariants();
    let len_before = sb.len();

    let article_uuid =
        uuid::Uuid::new_v5(base_uuid, article.html_path.to_string_lossy().as_bytes());
    write!(
        sb,
        r#"
<entry>
<title>{}</title>
<link href="{}/{}"/>
<id>urn:uuid:{}</id>
<updated>{}</updated>
<published>{}</published>
</entry>
    "#,
        text_sanitize_for_html(&article.text_title, true),
        BASE_URL,
        article
            .html_path
            .to_str()
            .ok_or(anyhow!("failed to convert path to str"))?,
        &article_uuid,
        article.git_stat.modification_date,
        article.git_stat.creation_date,
    )?;

    assert!(sb.len() > len_before);

    Ok(())
}

fn generate_rss(articles: &mut [Article]) -> anyhow::Result<()> {
    let start = Instant::now();

    let sb = rss_build(articles)?;
    assert!(!sb.is_empty());
    fs::write("feed.xml", sb).context("failed to write feed.xml")?;

    println!(
        "⚙️ generated feed.xml: {} us",
        Instant::now().duration_since(start).as_micros()
    );

    Ok(())
}

fn rss_build(articles: &mut [Article]) -> anyhow::Result<Vec<u8>> {
    articles.sort_by(|a, b| {
        a.git_stat
            .creation_date
            .as_str()
            .cmp(&b.git_stat.creation_date)
    });

    // The entries are written in this order, and the `<updated>` below assumes
    // it is not the order of modification dates.
    assert!(
        articles
            .windows(2)
            .all(|w| w[0].git_stat.creation_date <= w[1].git_stat.creation_date)
    );

    let mut sb = Vec::with_capacity(32000);
    let blog_uuid = uuid::Builder::from_bytes(FEED_UUID).into_uuid();

    // `articles` is sorted by creation date, and the most recently created
    // article is not necessarily the most recently modified one.
    let last_modification_date = articles
        .iter()
        .map(|a| a.git_stat.modification_date.as_str())
        .max()
        .ok_or(anyhow!("no article to build the feed from"))?;

    // It is the feed's `<updated>`: nothing inside the feed may be newer than
    // the feed itself.
    for a in articles.iter() {
        a.assert_invariants();
        assert!(a.git_stat.creation_date.as_str() <= last_modification_date);
        assert!(a.git_stat.modification_date.as_str() <= last_modification_date);
    }

    writeln!(
        sb,
        r#"<?xml version="1.0" encoding="utf-8"?>
<feed xmlns="http://www.w3.org/2005/Atom">
<title>Philippe Gaultier's blog</title>
<link href="{}"/>
<updated>{}</updated>
<author>
  <name>Philippe Gaultier</name>
</author>
<id>urn:uuid:{}</id>
"#,
        BASE_URL, last_modification_date, blog_uuid,
    )?;

    for a in articles {
        generate_article_rss(&mut sb, &blog_uuid, a)?;
    }

    sb.extend(b"</feed>");

    // A feed reader rejects the document outright if either end is missing.
    assert!(sb.starts_with(b"<?xml"));
    assert!(sb.ends_with(b"</feed>"));

    Ok(sb)
}

